static char expected[PLAIN_CAPACITY];
static unsigned char unpacked[PLAIN_CAPACITY];

static bool make_expected(void)
{
    char pair[3] = "aA";
    bool fine = CHECK(PARTS > 0);
    int part;

    expected[0] = '\0';
    for (part = 0; fine && (part < PARTS); ++part) {
        pair[0] = (char)('a' + ((part * 7) % LETTERS));
        pair[1] = (char)('A' + ((part * 11) % LETTERS));
        fine = CHECK(text_append_two(expected, sizeof expected, pair, "e a ")) &&
               CHECK(text_append_number(expected, sizeof expected, (long)((part * 37) % THOUSAND)));
    }
    return fine;
}

bool test_a_stream_of_dynamic_codes_with_repeated_lengths_inflates(void)
{
    ByteBuffer plain = { unpacked, sizeof unpacked, 0U };
    ByteSpan packed = { PACKED, sizeof PACKED };
    size_t length;

    if (!make_expected() || !inflate_raw(packed, &plain)) {
        return false;
    }
    length = text_length(expected, sizeof expected);
    return (plain.size == length) && (memcmp(unpacked, expected, length) == 0);
}
